import {
  DefensiveLine,
  Difficulty,
  MentalityLevel,
  PlayStyle,
  PressingIntensity,
  TempoSetting,
  WidthSetting,
  type Fixture,
  type Manager,
  type MatchResult,
  type PersistentManagerMemory,
  type TacticalSetup,
  type TacticalTeamSummary,
} from "@/types";
import { clamp } from "@/database/rng";

export interface ManagerMemoryMatchContext {
  manager: Manager;
  fixture: Fixture;
  result: MatchResult;
  userClubId: string;
  seasonYear: number;
  week: number;
}

export function emptyManagerMemory(manager: Manager): PersistentManagerMemory {
  return {
    schemaVersion: 1,
    managerId: manager.id,
    clubId: manager.clubId,
    meetings: 0,
    lastUpdatedSeason: 0,
    lastUpdatedWeek: 0,
    encounters: [],
    observedFormations: {},
    observedPlayStyles: {},
    playerKnowledge: {},
    tacticalLessons: [],
    confidence: 0,
  };
}

/** Learn only from structured match evidence generated by the simulator. */
export function rememberManagerMatch(
  previous: PersistentManagerMemory | undefined,
  context: ManagerMemoryMatchContext,
): PersistentManagerMemory {
  const memory: PersistentManagerMemory = previous
    ? {
        ...previous,
        encounters: previous.encounters.map((encounter) => ({ ...encounter, topThreatPlayerIds: [...encounter.topThreatPlayerIds] })),
        observedFormations: { ...previous.observedFormations },
        observedPlayStyles: { ...previous.observedPlayStyles },
        playerKnowledge: Object.fromEntries(Object.entries(previous.playerKnowledge).map(([id, player]) => [id, { ...player }])),
        tacticalLessons: [...previous.tacticalLessons],
      }
    : emptyManagerMemory(context.manager);
  const { fixture, result } = context;
  const managerClubId = fixture.homeClubId === context.userClubId ? fixture.awayClubId : fixture.homeClubId;
  const managerIsHome = fixture.homeClubId === managerClubId;
  const userSide = managerIsHome ? "away" : "home";
  const goalsFor = managerIsHome ? result.homeGoals : result.awayGoals;
  const goalsAgainst = managerIsHome ? result.awayGoals : result.homeGoals;
  const formation = userSide === "home"
    ? result.analysis?.finalHomeFormation ?? "Unknown"
    : result.analysis?.finalAwayFormation ?? "Unknown";
  const playStyle = userSide === "home"
    ? result.analysis?.finalHomePlayStyle ?? PlayStyle.Balanced
    : result.analysis?.finalAwayPlayStyle ?? PlayStyle.Balanced;
  const summary = result.analysis?.teamSummaries?.[userSide];
  const userReports = Object.values(result.analysis?.players ?? {})
    .filter((player) => player.clubId === context.userClubId)
    .sort((a, b) =>
      b.goals * 5 + b.assists * 3 + b.rating + b.shots * 0.2 + b.keyPasses * 0.3 -
      (a.goals * 5 + a.assists * 3 + a.rating + a.shots * 0.2 + a.keyPasses * 0.3),
    );
  const topThreatPlayerIds = userReports.slice(0, 3).map((player) => player.playerId);

  memory.managerId = context.manager.id;
  memory.clubId = context.manager.clubId;
  memory.meetings += 1;
  memory.lastUpdatedSeason = context.seasonYear;
  memory.lastUpdatedWeek = context.week;
  memory.observedFormations[formation] = (memory.observedFormations[formation] ?? 0) + 1;
  memory.observedPlayStyles[playStyle] = (memory.observedPlayStyles[playStyle] ?? 0) + 1;
  memory.encounters.push({
    fixtureId: fixture.id,
    seasonYear: context.seasonYear,
    week: context.week,
    result: goalsFor > goalsAgainst ? "W" : goalsFor < goalsAgainst ? "L" : "D",
    goalsFor,
    goalsAgainst,
    userFormation: formation,
    userPlayStyle: playStyle,
    userExpectedGoals: summary?.expectedGoals ?? 0,
    userFieldTilt: summary?.fieldTilt ?? 50,
    userHighRegains: summary?.highRegains ?? 0,
    topThreatPlayerIds,
  });
  memory.encounters = memory.encounters.slice(-12);

  for (const report of userReports) {
    const known = memory.playerKnowledge[report.playerId];
    const meetings = (known?.meetings ?? 0) + 1;
    memory.playerKnowledge[report.playerId] = {
      playerId: report.playerId,
      playerName: report.playerName,
      meetings,
      goals: (known?.goals ?? 0) + report.goals,
      assists: (known?.assists ?? 0) + report.assists,
      averageRating: Number((((known?.averageRating ?? 0) * (meetings - 1) + report.rating) / meetings).toFixed(2)),
      shots: (known?.shots ?? 0) + report.shots,
      keyPasses: (known?.keyPasses ?? 0) + report.keyPasses,
      lastSeenSeason: context.seasonYear,
      lastSeenWeek: context.week,
    };
  }

  memory.confidence = Number(clamp(memory.meetings / 5, 0.18, 1).toFixed(2));
  memory.tacticalLessons = deriveLessons(memory, summary, userReports[0]?.playerName).slice(0, 6);
  return memory;
}

function deriveLessons(
  memory: PersistentManagerMemory,
  summary: TacticalTeamSummary | undefined,
  topThreatName?: string,
): string[] {
  const lessons: string[] = [];
  const style = mostFrequent(memory.observedPlayStyles as Record<string, number>);
  const formation = mostFrequent(memory.observedFormations);
  if (style) lessons.push(`Usually prepares ${humanize(style)} football`);
  if (formation) lessons.push(`Most often seen in ${formation}`);
  if (summary && summary.fieldTilt >= 58) lessons.push("Sustains pressure in the attacking third");
  if (summary && summary.highRegains >= 4) lessons.push("Can create chances from high regains");
  if (summary) {
    const channels: ["left" | "central" | "right", number][] = [
      ["left", summary.leftChannelActions],
      ["central", summary.centralChannelActions],
      ["right", summary.rightChannelActions],
    ];
    channels.sort((a, b) => b[1] - a[1]);
    if (channels[0][1] > channels[1][1] * 1.2) lessons.push(`Favours the ${channels[0][0]} attacking channel`);
  }
  if (topThreatName) lessons.push(`${topThreatName} was the latest primary threat`);
  return lessons;
}

export function adaptTacticsToManagerMemory(
  base: TacticalSetup,
  memory: PersistentManagerMemory | undefined,
  difficulty: Difficulty | string | undefined,
): { tactics: TacticalSetup; reasons: string[] } {
  const level = managerMemoryLevel(difficulty);
  const requiredMeetings = level <= 1 ? Infinity : level === 2 ? 3 : level === 3 ? 2 : 1;
  const tactics: TacticalSetup = {
    ...base,
    playerRoles: { ...(base.playerRoles ?? {}) },
    positionOverrides: { ...base.positionOverrides },
    setPieces: { ...base.setPieces },
  };
  if (!memory || memory.meetings < requiredMeetings) return { tactics, reasons: [] };

  const reasons: string[] = [];
  const style = mostFrequent(memory.observedPlayStyles as Record<string, number>) as PlayStyle | undefined;
  const latest = memory.encounters.at(-1);
  if (style === PlayStyle.WingPlay) {
    tactics.width = WidthSetting.Wide;
    tactics.pressing = PressingIntensity.High;
    reasons.push("remembers repeated wide attacks");
    if (level >= 5) tactics.formation = "4-5-1";
  } else if (style === PlayStyle.PossessionBased || style === PlayStyle.TikiTaka || style === PlayStyle.TotalFootball) {
    tactics.pressing = level >= 5 ? PressingIntensity.Extreme : PressingIntensity.High;
    tactics.tempo = TempoSetting.Fast;
    tactics.counterAttack = true;
    reasons.push("plans to disrupt the remembered possession build-up");
  } else if (
    style === PlayStyle.RouteOne || style === PlayStyle.LongBallDirect || style === PlayStyle.DirectCounterAttack
  ) {
    tactics.defensiveLine = DefensiveLine.Deep;
    tactics.mentality = MentalityLevel.Cautious;
    tactics.pressing = PressingIntensity.Standard;
    reasons.push("drops protection against the remembered direct threat");
  } else if (style === PlayStyle.GegenpressingStyle) {
    tactics.passingLength = TempoSetting.Fast;
    tactics.counterAttack = true;
    reasons.push("prepares to bypass the remembered counter-press");
  }
  if (level >= 4 && latest && latest.userFieldTilt >= 60) {
    tactics.defensiveLine = DefensiveLine.Deep;
    tactics.mentality = Math.min(tactics.mentality, MentalityLevel.Cautious);
    reasons.push("respects the territory conceded in the last meeting");
  }
  if (level >= 5 && latest && latest.userHighRegains >= 4) {
    tactics.passingLength = TempoSetting.Fast;
    tactics.tempo = TempoSetting.Fast;
    reasons.push("uses earlier outlets after remembered high-regain pressure");
  }
  return { tactics, reasons: [...new Set(reasons)] };
}

export function memoryPlayerThreatBonus(
  memory: PersistentManagerMemory | undefined,
  playerId: string,
  difficulty: Difficulty | string | undefined,
): number {
  const level = managerMemoryLevel(difficulty);
  const known = memory?.playerKnowledge[playerId];
  if (!known || level < 2) return 0;
  const recall = clamp((level - 1) / 5, 0.2, 1) * (memory?.confidence ?? 0);
  return (known.averageRating - 6) * 5 * recall + (known.goals * 2 + known.assists + known.keyPasses * 0.18) * recall;
}

export function managerMemoryLevel(difficulty: Difficulty | string | undefined): number {
  switch (difficulty) {
    case Difficulty.Beginner: return 0;
    case Difficulty.Amateur: return 1;
    case Difficulty.SemiPro: return 2;
    case Difficulty.Professional: return 3;
    case Difficulty.WorldClass: return 4;
    case Difficulty.Legend:
    case Difficulty.Legendary: return 5;
    case Difficulty.Ultimate: return 6;
    default: return 2;
  }
}

function mostFrequent(values: Record<string, number>): string | undefined {
  return Object.entries(values)
    .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))[0]?.[0];
}

function humanize(value: string): string {
  return value.replace(/([a-z])([A-Z])/g, "$1 $2").replace(/Style$/, "").toLowerCase();
}
