export const FORMATION_NAMES: string[] = FORMATIONS.map((fm) => fm.name);

export function getFormation(name: string): Formation {
  return FORMATIONS.find((fm) => fm.name === name) ?? FORMATIONS[2]; // default 4-3-3
}

/** Flip X coordinates for the away team (x = 1000 - x) */
export function mirrorFormation(formation: Formation): Formation {
  return {
    name: formation.name,
    positions: formation.positions.map((p: FormationSlot) => ({
      ...p,
      baseX: 1000 - p.baseX,
    })),
  };
}
